// xterm color themes. Keys match the ITheme shape from @xterm/xterm.

export interface XTermTheme {
  background: string
  foreground: string
  cursor: string
  cursorAccent: string
  selectionBackground: string
  black: string
  red: string
  green: string
  yellow: string
  blue: string
  magenta: string
  cyan: string
  white: string
  brightBlack: string
  brightRed: string
  brightGreen: string
  brightYellow: string
  brightBlue: string
  brightMagenta: string
  brightCyan: string
  brightWhite: string
}

// ColorScheme bundles an xterm palette with a `ui` flag telling the rest of
// the app whether to render its chrome in dark or light mode. `label` is shown
// in the settings dropdown. The set is modelled on popular terminal palettes
// (Dracula, One Dark, Gruvbox, Nord, Solarized, Monokai, Tokyo Night, GitHub,
// Catppuccin, Material Palenight, etc.).
export interface ColorScheme {
  label: string
  ui: 'dark' | 'light'
  theme: XTermTheme
}

