export function resolveScheme(key: string | undefined): ColorScheme {
  if (!key) return colorSchemes[DEFAULT_SCHEME]
  const k = LEGACY_ALIASES[key] ?? key
  return colorSchemes[k] ?? colorSchemes[DEFAULT_SCHEME]
}

export function resolveXTermTheme(key: string | undefined): XTermTheme {
  return resolveScheme(key).theme
}

export function schemeUi(key: string | undefined): 'dark' | 'light' {
  return resolveScheme(key).ui
}

// Backwards-compatible alias. New code should use resolveXTermTheme().
export const themes: Record<string, XTermTheme> = Object.fromEntries(
  Object.entries(colorSchemes).map(([k, v]) => [k, v.theme]),
)
